const mysqlInformationSchema: SqlSchema = {
  databases: [INFORMATION_SCHEMA],
  tables: Object.keys(MYSQL_INFORMATION_SCHEMA_COLUMNS).map((name) => ({
    name,
  })),
  columns: Object.entries(MYSQL_INFORMATION_SCHEMA_COLUMNS).flatMap(
    ([table, columns]) => columns.map((name) => ({ table, name }))
  ),
};

/** 系统库自身的名称与引用形式均不区分 ASCII 大小写。 */
export function getSqlCompletionSystemSchema(
  dialect: SqlDialect,
  namespace: string | null | undefined
): SqlSchema | undefined {
  return dialect === "mysql" && namespace?.toLowerCase() === INFORMATION_SCHEMA
    ? mysqlInformationSchema
    : undefined;
}

export function getSqlCompletionSystemNamespaces(
  dialect: SqlDialect
): string[] {
  return dialect === "mysql" ? [INFORMATION_SCHEMA] : [];
}
